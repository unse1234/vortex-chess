import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

const features = ["auth", "games", "lobby", "social"];

const noRelativeParentImports = {
  group: ["../*"],
  message: "Use the `@/` alias for imports outside the current folder.",
};

// Architectural boundaries from docs/Vortex_Chess_Frontend_Plan.md §3.2.
const boundaryRules = [
  {
    files: ["src/**/*.{ts,tsx}"],
    rules: {
      "no-restricted-imports": ["error", { patterns: [noRelativeParentImports] }],
    },
  },
  {
    // Shared layers never depend on domain modules, composition or mocks.
    files: [
      "src/components/**",
      "src/lib/**",
      "src/hooks/**",
      "src/utils/**",
      "src/config/**",
      "src/types/**",
      "src/styles/**",
    ],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          patterns: [
            noRelativeParentImports,
            {
              group: ["@/features/*", "@/screens/*", "@/app/*", "@/mocks/*", "@/providers/*"],
              message: "Shared code must stay domain-independent.",
            },
          ],
        },
      ],
    },
  },
  ...features.map((feature) => ({
    // Features own their domain; they never reach into composition, mocks or sibling features.
    files: [`src/features/${feature}/**`],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          patterns: [
            noRelativeParentImports,
            {
              group: ["@/screens/*", "@/app/*", "@/providers/*"],
              message: "Features are composed by screens, not the other way round.",
            },
            {
              group: ["@/mocks/*"],
              message: "Components and services read data through the API boundary, never fixtures.",
            },
            {
              group: ["@/features/*", `!@/features/${feature}`],
              message: "Compose sibling features in a screen instead of importing them.",
            },
          ],
        },
      ],
    },
  })),
];

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  ...boundaryRules,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated by `msw init`.
    "public/mockServiceWorker.js",
  ]),
]);

export default eslintConfig;
